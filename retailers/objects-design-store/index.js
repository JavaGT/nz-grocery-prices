import { ShopifyCatalogClient } from "../_lib/shopify.js";

export const RETAILER = {
  slug: "objects-design-store",
  name: "Objects Design Store",
  origin: "https://objectsdesignstore.com",
  platform: "shopify",
};

export function createClient(options = {}) {
  return new ShopifyCatalogClient({
    slug: RETAILER.slug,
    origin: RETAILER.origin,
    scopeName: "Objects Design Store Online",
    ...options,
  });
}
