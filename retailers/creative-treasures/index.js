import { ShopifyCatalogClient } from "../_lib/shopify.js";

export const RETAILER = {
  slug: "creative-treasures",
  name: "Creative Treasures NZ",
  origin: "https://creativetreasures.co.nz",
  platform: "shopify",
};

export function createClient(options = {}) {
  return new ShopifyCatalogClient({
    slug: RETAILER.slug,
    origin: RETAILER.origin,
    scopeName: "Creative Treasures NZ Online",
    ...options,
  });
}
