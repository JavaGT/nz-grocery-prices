import { ShopifyCatalogClient } from "../_lib/shopify.js";

export const RETAILER = {
  slug: "the-cosmetic-store",
  name: "The Cosmetic Store NZ",
  origin: "https://thecosmeticstore.co.nz",
  platform: "shopify",
};

export function createClient(options = {}) {
  return new ShopifyCatalogClient({
    slug: RETAILER.slug,
    origin: RETAILER.origin,
    scopeName: "The Cosmetic Store NZ Online",
    ...options,
  });
}
